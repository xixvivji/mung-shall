package com.example.backend.domain.survey.enums;

public enum RestActivityLevel {
    VERY_ACTIVE,    // 매우 활동적 (예: 격렬한 운동, 장시간 야외 활동)
    ACTIVE,         // 활동적 (예: 규칙적인 운동, 활발한 야외 활동)
    MODERATE,       // 보통 (예: 산책, 친구 만나기, 가벼운 활동)
    CALM,           // 차분함 (예: 집에서 휴식, 독서, 조용한 활동)
    VERY_CALM       // 매우 차분함 (예: 주로 실내 활동, 적은 움직임)
}
